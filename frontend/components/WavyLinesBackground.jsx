            wave1: { ...DEFAULT_WAVE_CONFIG.wave1, ...parsed.wave1 },
            wave2: { ...DEFAULT_WAVE_CONFIG.wave2, ...parsed.wave2 },
            global: { ...DEFAULT_WAVE_CONFIG.global, ...parsed.global },
