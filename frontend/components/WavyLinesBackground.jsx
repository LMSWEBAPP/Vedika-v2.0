    setWaveConfig(prev => {
      const next = {
        ...prev,
        [section]: {
          ...prev[section],
          [key]: Number(value)
        }
      };
      try {
        localStorage.setItem('vedika_wavy_bg_config_v1', JSON.stringify(next));
      } catch (e) {}
      return next;
    });
